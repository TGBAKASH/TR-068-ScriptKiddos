# Normalize subject names - handles common field worker input variations
SUBJECT_ALIASES = {
    "maths": "Math", "mathematics": "Math", "math": "Math",
    "english": "English", "eng": "English",
    "science": "Science", "sci": "Science",
    "hindi": "Hindi", "hnd": "Hindi",
    "evs": "EVS", "environmental studies": "EVS",
    "social": "Social Studies", "social science": "Social Studies",
    "sst": "Social Studies", "social studies": "Social Studies"
}

def normalize_subject(name):
    return SUBJECT_ALIASES.get(name.lower().strip(), name.strip().title())

def get_curriculum(class_str, subject):
    """Get NCERT curriculum topics for a given class and subject."""
    class_str = str(class_str).strip()
    subject = normalize_subject(subject)
    
    class_data = NCERT_CURRICULUM.get(class_str, {})
    return class_data.get(subject, {
        "all_topics": [],
        "beginner": ["Core concepts review"],
        "intermediate": ["Intermediate practice"],
        "advanced": ["Advanced application"]
    })
